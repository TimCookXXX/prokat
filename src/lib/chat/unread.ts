// Единственное правило о том, считается ли сообщение непрочитанным для
// смотрящего. Модуль чистый — базы не знает, поэтому покрыт тестами без живого
// Postgres, как и остальные правила чата.
//
// Правило одно, а применяется в двух мирах: SQL считает счётчики (три выборки
// в server/chat.ts зовут unreadCondition, собранный по этой же формуле), а
// клиент рисует разделитель «непрочитанные» в ленте треда. Разъехавшись, они
// дали бы точку, которая горит по одному правилу и гаснет по другому.
//
// Системная запись непрочитанной не бывает НИКОГДА, и это не следствие пустого
// отправителя, а отдельное условие. Разница существенная: у системной записи
// `senderUserId` пуст, а `null !== viewerId` истинно — то есть на сравнении с
// отправителем правило молча посчитало бы своей же заявкой чужое сообщение и
// подняло бы счётчик у обеих сторон.

export type UnreadCandidate = {
  id: string;
  kind: string;
  senderUserId: string | null;
};

export function isUnreadFor(
  message: UnreadCandidate,
  viewerId: string,
  /** id последнего прочитанного; пусто — не читал ничего. */
  cursor: string | null,
): boolean {
  if (message.kind !== "user") return false;
  // Автора нет — считать нечего. Схема такую строку не допускает
  // (chat_messages_kind_shape), но без этой строки правило расходилось бы со
  // своей же половиной в SQL: там `sender_user_id <> $1` при NULL даёт NULL и
  // строку отбрасывает, а `null === viewerId` здесь ложно.
  if (!message.senderUserId) return false;
  if (message.senderUserId === viewerId) return false;
  // ULID сравнивается лексикографически, поэтому пустой курсор делает
  // непрочитанным всё.
  return message.id > (cursor ?? "");
}
