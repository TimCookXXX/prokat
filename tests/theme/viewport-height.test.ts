import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";

/* Сторож высоты, посчитанной от вьюпорта.
 *
 * Панель переписки на десктопе берёт высоту как «экран минус обложка с героем».
 * Пока экран высокий, это верно. Но телефон, повёрнутый на бок, даёт ширину
 * 844 и высоту 390: раскладка переключается на десктопную (сайдбар живёт с md),
 * а вычитаемые 292px обложки никуда не деваются — и разность даёт 74px. В
 * панель такой высоты не помещается ни строка списка, ни поле ввода.
 *
 * Ни tsc, ни vitest этого не видят: высота живёт строкой класса Tailwind и
 * считается браузером. Поэтому проверка читает исходник — тот же приём, что у
 * сторожа состояний по соседству.
 *
 * Обещание «панель помещается без прокрутки страницы» на 390px выполнить
 * нечем, и честный ответ здесь — прокрутка, а не нерабочая панель. Значит у
 * разности обязан быть ПОЛ. */

const FILE = "src/components/chat/ChatPanes.tsx";

describe("высота панели переписки", () => {
  const src = readFileSync(FILE, "utf8");

  // Все арбитрарные высоты, которые вычитают что-то из высоты вьюпорта.
  const derived = [...src.matchAll(/h-\[[^\]]*(?:svh|dvh|vh)[^\]]*\]/g)]
    .map((m) => m[0])
    .filter((v) => v.includes("calc(") && v.includes("-"));

  it("такая высота в файле есть — иначе проверять нечего", () => {
    expect(derived.length).toBeGreaterThan(0);
  });

  it("у каждой есть пол: без него телефон на боку схлопывает панель", () => {
    for (const value of derived) {
      expect(value, `${value} — разность без max(): на низком экране уйдёт в ноль`)
        .toContain("max(");
    }
  });

  /* Пол должен быть пригодным для работы, а не формальным. В панели живут
   * шапка переписки, хотя бы пара сообщений и поле ввода. */
  it("пол не меньше 20rem", () => {
    for (const value of derived) {
      const floor = /max\((\d+(?:\.\d+)?)rem/.exec(value);
      expect(floor, `${value} — пол задан не в rem, проверить вручную`).not.toBeNull();
      expect(Number(floor?.[1])).toBeGreaterThanOrEqual(20);
    }
  });
});
