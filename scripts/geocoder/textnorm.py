#!/usr/bin/env python3
"""Нормализация названий для импорта геокодера: улицы, номера домов, пункты, СНТ, ЖК.

Правила — для СОПОСТАВЛЕНИЯ источников (OSM ↔ ГАР, склейка дублей) и для канонической подписи.
Поисковые правила (опечатки, раскладка, падежи) — в src/lib/geocoder, не здесь.

  python textnorm.py --selftest     # проверки на примерах из разведки
"""
import re
import sys

ZW = re.compile("[​‌‍⁠﻿­]")
QUOTES = re.compile("[«»\"“”„'`’]")

# Тип улицы: каноническое слово → написания (полные и сокращения; сравнение без точки и регистра).
STREET_TYPES = {
    "улица": ["улица", "ул", "у"],
    "проспект": ["проспект", "пр-кт", "пр-т", "просп", "прт", "пркт"],
    "переулок": ["переулок", "пер", "пер-к"],
    "проезд": ["проезд", "пр-д", "прд"],
    "бульвар": ["бульвар", "б-р", "бул", "бульв"],
    "площадь": ["площадь", "пл"],
    "шоссе": ["шоссе", "ш"],
    "набережная": ["набережная", "наб"],
    "тупик": ["тупик", "туп"],
    "аллея": ["аллея", "ал"],
    "линия": ["линия", "лн"],
    "микрорайон": ["микрорайон", "мкр", "мкрн", "мкр-н"],
    "квартал": ["квартал", "кв-л"],
    "территория": ["территория", "тер"],
    "дорога": ["дорога", "дор"],
    "въезд": ["въезд"],
    "спуск": ["спуск"],
    "тракт": ["тракт"],
    "разъезд": ["разъезд", "рзд"],
    "проулок": ["проулок", "проул"],
    "сквер": ["сквер", "с-р"],
    "парк": ["парк"],
    "километр": ["километр", "км"],
}
TYPE_OF = {}
for _canon, _vars in STREET_TYPES.items():
    for _v in _vars:
        TYPE_OF[_v] = _canon
# Сокращения, которые без точки легко спутать со словом («ал», «у», «ш», «пл», «км») — тип только с точкой
# или если это не единственное слово.
AMBIGUOUS_ABBR = {"у", "ш", "ал", "пл", "парк", "км", "лн"}
FEM_TYPES = {"улица", "набережная", "площадь", "аллея", "линия", "дорога", "территория"}
MASC_TYPES = {"проспект", "переулок", "проезд", "бульвар", "тупик", "микрорайон", "квартал", "въезд",
              "спуск", "тракт", "разъезд", "проулок", "сквер", "парк", "километр"}
NEUT_TYPES = {"шоссе"}
# Тип «после имени» у прилагательных: «Рождественская набережная», «Ростовское шоссе», «1-й Лиговский проезд».
# «улица» всегда впереди: «улица Красная» (как в ГАР и в подсказке контракта).
PREFIX_ALWAYS = {"улица", "микрорайон", "квартал", "территория", "километр"}
ADJ_END = {"fem": ("ая", "яя"), "masc": ("ый", "ий", "ой"), "neut": ("ое", "ее")}

ORD = re.compile(r"^(\d+)(?:-?(?:й|я|е|ой|ый|ий|ая|ое|ье|го|ого|ему))?$")
ORD_NOM = re.compile(r"^\d+-?(?:й|я|е|ой|ый|ий|ая|ое|ье)$")
INITIALS = re.compile(r"(?<![А-Яа-яЁё])[А-ЯЁ]\.\s?(?:[А-ЯЁ]\.\s?)?")


def clean(s):
    """Невидимые символы, кавычки, лишние пробелы; «(СНТ Кубаночка)» в хвосте имени улицы — прочь."""
    if not s:
        return ""
    s = ZW.sub("", s)
    s = s.replace(" ", " ").replace("–", "-").replace("—", "-")
    s = QUOTES.sub("", s)
    s = re.sub(r"\s*\((?:снт|ст|нст|днт|тсн|сот)[^)]*\)\s*$", "", s, flags=re.I)
    return re.sub(r"\s+", " ", s).strip(" ,;")


def low(s):
    return clean(s).lower().replace("ё", "е")


def _tokens(s):
    """Слова с точкой-сокращением: «ул.Красная» → ['ул.', 'Красная']; «пр-кт» остаётся целым."""
    s = re.sub(r"(?<=[А-Яа-яЁё])\.(?=[А-Яа-яЁё])", ". ", clean(s))
    return [t for t in s.replace(",", " ").split() if t]


def split_street(name):
    """«Красная улица» → ('Красная', 'улица'); «ул. им. Тургенева» → ('им. Тургенева', 'улица');
    «1-й переулок Ленина» → ('1-й Ленина', 'переулок'); без типа → (имя, '').
    Несколько слов-типов: тип — сокращение («ул. Адыгейская Набережная»), затем «улица» («Набережная улица»),
    затем слово в конце, в начале, в середине; остальные остаются в имени."""
    toks = _tokens(name)
    if len(toks) < 2:
        return " ".join(toks), ""
    cands = []
    for i, t in enumerate(toks):
        k = t.lower().rstrip(".").replace("ё", "е")
        canon = TYPE_OF.get(k)
        if not canon:
            continue
        if k in AMBIGUOUS_ABBR and not t.endswith(".") and not (i == 0 or i == len(toks) - 1):
            continue
        abbr = k != canon or t.endswith(".")
        edge = 1 if i == len(toks) - 1 else 2 if i == 0 else 3
        cands.append(((0 if abbr else 1 if canon == "улица" else 1 + edge), i, canon))
    if not cands:
        return " ".join(toks), ""
    _, i, typ = min(cands)
    core = toks[:i] + toks[i + 1:]
    if typ == "линия" and i > 0 and ORD.match(toks[i - 1].lower()):
        # «1-я линия» — имя и тип сразу: ядро «1-я линия» (иначе «линия 1-я»).
        core = toks[:i] + [toks[i].lower()] + toks[i + 1:]
    return " ".join(core).strip(), typ


ROMAN = {"i": 1, "v": 5, "x": 10, "l": 50}


def _roman(w):
    """«XXI», «ХХ1» (кириллица и единица вместо I) → 21; не римское — None."""
    if not re.search(r"[xхvi]", w.lower()):
        return None                                        # «11» — число, не римское
    s = w.lower().replace("х", "x").replace("і", "i").replace("1", "i")
    s = re.sub(r"-?(?:го|й|я|е|ого)$", "", s)
    if not s or not re.fullmatch(r"[xvil]+", s) or "x" not in s and len(s) < 2:
        return None
    total, prev = 0, 0
    for ch in reversed(s):
        v = ROMAN[ch]
        total = total - v if v < prev else total + v
        prev = max(prev, v)
    return total


def strip_honorifics(core):
    """«им. Калинина», «имени Калинина» → «Калинина»; инициалы «А.Б.Чуца», «Яцкова И.В.» → без них."""
    s = re.sub(r"(?i)(?:^|\s)(?:имени|им\.?)(?=\s|$)", " ", " " + core)
    s = INITIALS.sub(" ", s)
    return re.sub(r"\s+", " ", s).strip()


def effective_type(name):
    """Тип для сравнения одноимённых улиц: «ул. Ростовское Шоссе», «улица Бульвар Строителей», «улица Кубанская
    Набережная» — это шоссе, бульвар и набережная (ГАР и OSM пишут то «ул. X Шоссе», то «X шоссе»). Подпись улицы
    не меняется, только сравнение типов при склейке."""
    core, typ = split_street(name)
    if typ != "улица":
        return typ
    words = core.split()
    if len(words) < 2:
        return typ
    for w in reversed(words):
        c = TYPE_OF.get(w.lower().rstrip(".").replace("ё", "е"))
        if c and c != "улица" and w.lower().rstrip(".") not in AMBIGUOUS_ABBR and c != "линия":
            return c
    return typ


def street_key(name):
    """Ключ сопоставления улицы: без типа, «им.», инициалов, пунктуации; ё→е; «1-й»→«1»;
    «40-летия»→«40 лет»; слова по алфавиту. Одна улица в OSM и ГАР даёт один ключ."""
    core, _ = split_street(name)
    core = strip_honorifics(core) or core
    # слова-типы внутри имени («ул. Адыгейская Набережная», «ул. Бульвар Строителей») — прочь, если есть другие
    words = core.split()
    rest = [w for w in words if TYPE_OF.get(w.lower().rstrip(".").replace("ё", "е")) not in STREET_TYPES
            or w.lower().rstrip(".") in AMBIGUOUS_ABBR]
    if rest and len(rest) < len(words) and not re.search(r"(?i)\bлиния\b", core):
        core = " ".join(rest)
    s = core.lower().replace("ё", "е")
    s = " ".join(str(_roman(w)) if _roman(w) else w for w in s.split())
    s = re.sub(r"(\d+)\s*-?\s*летия", r"\1 лет", s)
    s = re.sub(r"(?<=[а-я])-(?=[а-я])", "", s)          # Ново-Садовая = Новосадовая
    s = re.sub(r"[^0-9a-zа-я]+", " ", s)
    out = []
    for w in s.split():
        m = ORD.match(w)
        if m:
            out.append(m.group(1))
        elif w in ("й", "я", "е", "ой", "го", "ая"):
            continue                                      # хвост «1 - й»
        else:
            out.append(w)
    return " ".join(sorted(out))


# Звания и титулы в именах улиц: ГАР и OSM пишут их по-разному («ул. им. Героя Советского Союза Иванова» /
# «улица Генерала Иванова» / «улица Иванова»). Для сопоставления источников — второй ключ без них.
