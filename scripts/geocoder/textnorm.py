LAT2CYR = str.maketrans({"a": "а", "b": "б", "c": "с", "e": "е", "h": "н", "k": "к", "m": "м", "o": "о",
                         "p": "р", "t": "т", "x": "х", "y": "у", "f": "ф", "d": "д", "g": "г"})


def number_norm(hn):
    """Ключ номера: «22 к2», «22 корп. 2», «22К2» → «22к2»; «151 стр 2», «151 с2» → «151с2»; «15 А», «15-а» → «15а»;
    «7 литБ», «7 лит. Б» → «7литб»; «174\\3», «174//3» → «174/3»; латиница → кириллица; «уч615» → «615»."""
    s = clean(hn).lower().replace("ё", "е").translate(LAT2CYR)
    s = s.replace("\\", "/")
    s = re.sub(r"/+", "/", s)
    s = re.sub(r"^(?:д|дом|уч|участок|влд|двлд|зд)\.?\s*(?=\d)", "", s)
    s = re.sub(r"корпус|корп\.?|кор\.?|к\.", "к", s)
    s = re.sub(r"строение|стр\.?|с\.", "с", s)
    s = re.sub(r"сооружение|соор\.?", "соор", s)
    s = re.sub(r"литера|литер|лит\.?", "лит", s)
    s = re.sub(r"[\s,\.\"'«»]+", "", s)
    s = re.sub(r"(\d)-([а-я])$", r"\1\2", s)      # 15-а → 15а; диапазон 482-483 остаётся
    s = s.strip("/-")
    return s


def number_display(hn):
    """Номер для подписи: «22 к2» → «22к2», «15 а» → «15А», «151 стр 2» → «151с2», «7 лит. Б» → «7литБ»."""
    n = number_norm(hn)
    # Буква сразу после цифры или «/» — заглавная: 15а → 15А, 14/7б → 14/7Б, 21/а → 21/А.
    n = re.sub(r"(?<=[\d/])([абвгдежзийклмнопрстуфхцчшщэюя])(?![а-я\d])", lambda m: m.group(1).upper(), n)
    n = re.sub(r"лит([а-я])", lambda m: "лит" + m.group(1).upper(), n)
    return n


def number_base(hn_norm):
    """Целая часть номера для интерполяции: «21к1» → 21, «14/7Б» → 14, «уч615» → 615; нет — None."""
    m = re.match(r"^(\d{1,5})", hn_norm)
    return int(m.group(1)) if m else None


def gar_number(housenum, addtype1="", addnum1="", addtype2="", addnum2="", housetype=""):
    """Номер ГАР в формате OSM: «21» + к.1 → «21к1»; стр.2 → «21с2»; литера А → «21литА»; соор. → «21соор1»."""
    parts = [housenum.strip()]
    for t, v in ((addtype1, addnum1), (addtype2, addnum2)):
        v = (v or "").strip()
        if not v:
            continue
        suf = {"к.": "к", "стр.": "с", "соор.": "соор", "литера": "лит"}.get(t, "")
        parts.append(suf + v)
    return "".join(parts)


