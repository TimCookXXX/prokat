    "рядового", "народного", "артиста", "художника", "композитора", "врача", "доктора", "святого", "святых",
    "кавалера", "почетного", "гражданина", "командарма", "комдива", "комиссара", "партизана", "партизанки",
    "учителя", "архитектора", "инженера", "конструктора", "матроса", "гвардии", "старшины", "ефрейтора",
