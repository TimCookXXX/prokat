const args = process.argv.slice(2);
const opt = (n: string, d: string) => (args.indexOf(n) >= 0 ? args[args.indexOf(n) + 1] : d);
const mod = await import(resolve(opt("--engine", resolve(ROOT, "src/lib/geocoder")), "engine.ts"));
const data = JSON.parse(readFileSync(resolve(ROOT, opt("--index", "data/geocoder/build/index.krasnodar.json")), "utf8"));
const g = mod.createGeocoder(data);
const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");
const verbose = args.includes("--v");
const only = opt("--only", "");
let ok = 0;
let n = 0;
type Hit = { title: string; subtitle: string; kind: string; precision: string; score: number };
for (const c of CASES) {
  if (only && !c.q.includes(only)) continue;
  const hits: Hit[] = g.suggest(c.q);
  const geo: { hit: Hit | null; reason: string | null } = g.geocodeDetailed(c.q);
  const match = (h: Hit | null | undefined) => !!h && norm(h.title).includes(norm(c.t)) && (!c.s || norm(`${h.subtitle} ${h.title}`).includes(norm(c.s)));
  const res: string[] = [];
  let good = true;
  for (const m of c.m) {
    const same = () => {
      const r: { hit: Hit | null; reason: string | null } = g.geocodeDetailed(c.ref ?? c.q);
      return r.reason === geo.reason && r.hit?.title === geo.hit?.title && r.hit?.subtitle === geo.hit?.subtitle;
    };
    const pass = m === "top1" ? match(hits[0]) : m === "top5" ? hits.slice(0, 5).some(match) : m === "geo" ? match(geo.hit) : m === "georef" ? same() : !geo.hit || match(geo.hit);
    res.push(`${m}:${pass ? "ok" : "FAIL"}`);
    if (!pass) good = false;
  }
  n++;
  if (good) ok++;
  if (!good || verbose) {
    console.log(`${good ? "  " : "✗ "}«${c.q}» → ${c.t}${c.s ? " | " + c.s : ""}  ${res.join(" ")}`);
    for (const h of hits.slice(0, 5)) console.log(`      ${h.score.toFixed(1).padStart(6)} ${h.kind.padEnd(6)} ${h.precision.padEnd(12)} ${h.title} — ${h.subtitle}`);
    console.log(`      geocode: ${geo.hit ? `${geo.hit.title} — ${geo.hit.subtitle} [${geo.hit.kind}/${geo.hit.precision}]` : "null " + geo.reason}`);
  }
}
console.log(`\nпрошло ${ok} из ${n}`);
